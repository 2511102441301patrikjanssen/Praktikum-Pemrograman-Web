// operator aritmatika

let x = 10;
let y = 20;
let hasil;

// penjumlahan
hasil = x + y;
console.log(hasil);

// pengurangan
hasil = y - x;
console.log(hasil);

// perkalian
hasil = x * y;
console.log(hasil);

// pembagian
hasil = y / x;
console.log(hasil);

// modulus
hasil = y % x;
console.log(hasil);


// operator logika

// AND (&&) => jika dua nilai bernilai true
x = true;
y = false;

hasil = x && y;
console.log(hasil);

// OR (||) => jika salah satu nilai bernilai true
hasil = x || y;
console.log(hasil);